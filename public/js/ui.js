export function ic(name, size = 18) {
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24">${ICONS[name] || ''}</svg>`;
}

export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function displayTitle(value) {
  return String(value || '').replace(/^#+\s*/, '').trim();
}

export function initials(name) {
  return String(name || '?').split(' ').filter(Boolean).map((w) => w[0]).slice(0, 2).join('').toUpperCase();
}

export function ring(pct, size = 78, stroke = 7, color = 'var(--teal)') {
  const r = (size - stroke) / 2;
  const c = 2 * Math.PI * r;
  const off = c * (1 - Math.max(0, Math.min(100, pct)) / 100);
  return `<svg width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
    <circle cx="${size / 2}" cy="${size / 2}" r="${r}" stroke="var(--line)" stroke-width="${stroke}" fill="none"/>
    <circle class="ring-arc" cx="${size / 2}" cy="${size / 2}" r="${r}" stroke="${color}" stroke-width="${stroke}" fill="none"
      stroke-linecap="round" stroke-dasharray="${c}" stroke-dashoffset="${off}" style="transition:stroke-dashoffset .4s linear"/>
  </svg>`;
}

export function liteFx() {
  try {
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return true;
    const conn = navigator.connection;
    if (conn && (conn.saveData || /2g/i.test(conn.effectiveType || ''))) return true;
    const coarse = window.matchMedia('(pointer: coarse)').matches;
    const small = window.innerWidth < 700;
    const lowCpu = Number(navigator.hardwareConcurrency || 8) <= 4;
    if (coarse && small && lowCpu) return true;
  } catch (_) { /* ignore */ }
  return false;
}

